export const getProduct = (slug: string) => products.find((p) => p.slug === slug);
export const getProductById = (id: string) => products.find((p) => p.id === id);

export const newArrivals = () => [...products].filter((p) => p.isNew).sort((a, b) => b.createdAt.localeCompare(a.createdAt));
export const bestSellers = () => products.filter((p) => p.isBestSeller).sort((a, b) => b.reviewCount - a.reviewCount);
export const trending = () => products.filter((p) => p.isTrending);
export const onSale = () => products.filter((p) => p.compareAtPrice);
export const byCollection = (slug: string) => products.filter((p) => p.collection.includes(slug));
export const byCategory = (slug: string) => products.filter((p) => p.category === slug);

export function related(p: Product, n = 8) {
  return products
    .filter((x) => x.id !== p.id)
    .map((x) => ({
      x,
      s: (x.category === p.category ? 3 : 0) + x.collection.filter((c) => p.collection.includes(c)).length + (x.isBestSeller ? 0.5 : 0),
    }))
    .sort((a, b) => b.s - a.s)
    .slice(0, n)
    .map((r) => r.x);
}

export function variantStock(p: Product, color: string, size: string) {
  return p.variants.find((v) => v.color === color && v.size === size)?.stock ?? 0;
}

export function imagesFor(p: Product, color?: string) {
  const c = p.colors.find((x) => x.name === color);
  return c?.images ?? p.images;
}
