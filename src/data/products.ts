function hash(s: string) {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) h = Math.imul(h ^ s.charCodeAt(i), 16777619);
  return Math.abs(h);
}

type Input = Omit<
  Product,
  "id" | "currency" | "discount" | "variants" | "stock" | "sku" | "badge" | "isTrending" | "ratingBreakdown" | "tags"
> & {
  idx: number;
  isTrending?: boolean;
  tags?: string[];
  stockOverrides?: Record<string, number>; // "Color|Size" or "*|Size"
};

function make(i: Input): Product {
  const base = `TW-${i.category.slice(0, 3).toUpperCase()}-${String(i.idx).padStart(3, "0")}`;
  const variants: ProductVariant[] = [];
  for (const c of i.colors) {
    for (const s of i.sizes) {
      const key = `${c.name}|${s}`;
      let stock = (hash(i.slug + key) % 26) + 2;
      if (hash(key + i.slug) % 11 === 0) stock = 0;
      else if (hash(i.slug + s) % 7 === 0) stock = (hash(key) % 4) + 1;
      if (i.stockOverrides?.[key] !== undefined) stock = i.stockOverrides[key];
      else if (i.stockOverrides?.[`*|${s}`] !== undefined) stock = i.stockOverrides[`*|${s}`];
      variants.push({
        sku: `${base}-${c.name.replace(/[^A-Za-z]/g, "").slice(0, 3).toUpperCase()}-${s.replace(/\s/g, "")}`,
        color: c.name,
        size: s,
        stock,
      });
    }
  }
  const discount = i.compareAtPrice ? Math.round((1 - i.price / i.compareAtPrice) * 100) : undefined;
  const badge: Badge | undefined = i.isLimitedEdition
    ? "Limited Edition"
    : discount
      ? "Sale"
      : i.isNew
        ? "New"
        : i.isBestSeller
          ? "Bestseller"
          : undefined;
  const r = i.rating;
  const { idx: _idx, stockOverrides: _so, ...rest } = i;
  void _idx;
  void _so;
  return {
    ...rest,
    id: `p_${String(i.idx).padStart(3, "0")}`,
    currency: "INR",
    discount,
    variants,
    stock: variants.reduce((a, v) => a + v.stock, 0),
    sku: base,
    badge,
    isTrending: i.isTrending ?? false,
    tags: i.tags ?? [],
    ratingBreakdown: {
      quality: Math.min(5, +(r + 0.1).toFixed(1)),
      fit: +(r - 0.1).toFixed(1),
      value: +(r - 0.1).toFixed(1),
    },
  };
}

